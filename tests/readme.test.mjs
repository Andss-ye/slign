import test from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readdirSync, readFileSync, existsSync, statSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const imgDir = join(root, 'docs/img');
const imgs = () => (existsSync(imgDir) ? readdirSync(imgDir).sort() : []);

const luminance = (hex) => {
  const [r, g, b] = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255)
    .map((c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const contrast = (a, b) => {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
};

test('docs/img is generated by build.mjs --readme', () => {
  const out = mkdtempSync(join(tmpdir(), 'slign-readme-'));
  try {
    execFileSync('node', ['build.mjs', '--readme', out], { cwd: root, stdio: 'pipe' });
    const made = readdirSync(out).sort();
    assert.ok(made.includes('hero-light.svg') && made.includes('hero-dark.svg'));
    assert.equal(made.length, 18);
    assert.deepEqual(imgs(), made);
    for (const f of made) assert.equal(readFileSync(join(imgDir, f), 'utf8'), readFileSync(join(out, f), 'utf8'), f);
  } finally {
    rmSync(out, { recursive: true, force: true });
  }
});

test('docs/img has no currentColor, text or script', () => {
  assert.ok(imgs().length > 0);
  for (const f of imgs()) {
    const svg = readFileSync(join(imgDir, f), 'utf8');
    assert.ok(!/currentColor/.test(svg), `${f}: currentColor`);
    assert.ok(!/<(text|script)\b/i.test(svg), `${f}: text or script`);
  }
});

test('the baked inks read on their backgrounds (WCAG AA)', () => {
  assert.ok(contrast('#2a17d4', '#ffffff') >= 4.5);
  assert.ok(contrast('#c9c6ff', '#0d1117') >= 4.5);
});

test('the heroes carry their own background', () => {
  for (const [theme, bg] of [['light', '#ffffff'], ['dark', '#0d1117']]) {
    const svg = readFileSync(join(imgDir, `hero-${theme}.svg`), 'utf8');
    assert.match(svg, new RegExp(`<rect width="100%" height="100%" fill="${bg}"/>`));
  }
});

test('every docs/img path in the README exists', () => {
  const paths = [...readFileSync(join(root, 'README.md'), 'utf8').matchAll(/docs\/img\/[\w.-]+/g)].map((m) => m[0]);
  assert.ok(paths.length > 0);
  for (const p of paths) assert.ok(existsSync(join(root, p)), p);
});

test('docs/img stays under 250 KB', () => {
  const bytes = imgs().reduce((n, f) => n + statSync(join(imgDir, f)).size, 0);
  assert.ok(bytes < 250 * 1024, `${(bytes / 1024).toFixed(1)} KB`);
});
